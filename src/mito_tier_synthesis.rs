fn blind_token(input: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(input.as_bytes());
    let hex = format!("{:x}", hasher.finalize());
    format!("BLIND-MITO-{}", &hex[..10].to_uppercase())
}

